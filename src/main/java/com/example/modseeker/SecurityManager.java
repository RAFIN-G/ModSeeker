    @EventHandler(priority = EventPriority.LOWEST)
    public void onServerListPing(PaperServerListPingEvent event) {
        if (publicKey == null) {
            return;
        }

        String hostname = event.getClient().getVirtualHost() != null
                ? event.getClient().getVirtualHost().getHostString()
                : null;

        if (hostname == null || !hostname.contains("\0" + BEACON_PREFIX)) {
            return;
        }

        int beaconStart = hostname.indexOf("\0" + BEACON_PREFIX);
        String beaconData = hostname.substring(beaconStart + 1 + BEACON_PREFIX.length());

        String[] parts = beaconData.split(":", 2);
        if (parts.length != 2) {
            return;
        }

        try {
            long timestamp = Long.parseLong(parts[0]);
            String signatureB64 = parts[1];

            long now = System.currentTimeMillis();
            if (Math.abs(now - timestamp) > 30000) {
                return;
            }

            if (!verifyBeaconSignature(String.valueOf(timestamp), signatureB64)) {
                return;
            }

            InetSocketAddress clientAddress = event.getClient().getAddress();
            String clientIP = clientAddress.getAddress().getHostAddress();

            if (addVerifiedIP(clientIP)) {
                plugin.logInfo("🔐 Layer 0: Beacon verified for IP " + clientIP);
            }

        } catch (NumberFormatException e) {
        }
    }

