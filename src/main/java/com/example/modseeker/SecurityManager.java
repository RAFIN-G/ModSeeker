    /**
     * Add a verified IP to the beacon cache
     * 
     * @param ip The IP address
     * @return true if added, false if rate limited or cache full
     */
    public boolean addVerifiedIP(String ip) {
        if (ip == null || ip.isEmpty()) {
            return false;
        }

        long now = System.currentTimeMillis();

        // Check rate limit
        Long lastPing = rateLimitMap.get(ip);
        if (lastPing != null && (now - lastPing) < BEACON_RATE_LIMIT_MS) {
            return false; // Rate limited, silently ignore
        }

        // Update rate limit timestamp
        rateLimitMap.put(ip, now);

        // Check size limit - remove oldest entries if needed
        if (verifiedIPs.size() >= BEACON_MAX_SIZE) {
            cleanupExpiredBeacons();

            // If still full, remove oldest
            if (verifiedIPs.size() >= BEACON_MAX_SIZE) {
                removeOldestBeacon();
            }
        }

        // Add to cache
        verifiedIPs.put(ip, now + BEACON_EXPIRY_MS);
        return true;
    }

    /**
     * Check if an IP is verified (has a valid beacon)
     */
    public boolean isIPVerified(String ip) {
        if (ip == null || ip.isEmpty()) {
            return false;
        }

        Long expiry = verifiedIPs.get(ip);
        if (expiry == null) {
            return false;
        }

        // Check if expired
        if (System.currentTimeMillis() > expiry) {
            verifiedIPs.remove(ip);
            return false;
        }

        return true;
    }

    /**
     * Remove an IP from beacon cache (one-time use after login)
     */
    public void removeVerifiedIP(String ip) {
        if (ip != null) {
            verifiedIPs.remove(ip);
        }
    }

    /**
     * Clean up expired beacon entries
     */
    public void cleanupExpiredBeacons() {
        long now = System.currentTimeMillis();

        // Cleanup verified IPs
        Iterator<Map.Entry<String, Long>> it = verifiedIPs.entrySet().iterator();
        while (it.hasNext()) {
            if (now > it.next().getValue()) {
                it.remove();
            }
        }

        // Cleanup rate limit map (entries older than rate limit window)
        Iterator<Map.Entry<String, Long>> rateLimitIt = rateLimitMap.entrySet().iterator();
        while (rateLimitIt.hasNext()) {
            if (now - rateLimitIt.next().getValue() > BEACON_RATE_LIMIT_MS * 2) {
                rateLimitIt.remove();
            }
        }
    }

    private void removeOldestBeacon() {
        String oldestIP = null;
        long oldestTime = Long.MAX_VALUE;

        for (Map.Entry<String, Long> entry : verifiedIPs.entrySet()) {
            long addedTime = entry.getValue() - BEACON_EXPIRY_MS;
            if (addedTime < oldestTime) {
                oldestTime = addedTime;
                oldestIP = entry.getKey();
            }
        }

        if (oldestIP != null) {
            verifiedIPs.remove(oldestIP);
        }
    }

