    /**
     * Freeze a player (block all actions during verification)
     */
    public void freezePlayer(UUID playerId) {
        frozenPlayers.add(playerId);
    }

    /**
     * Unfreeze a player (allow all actions after verification)
     */
    public void unfreezePlayer(UUID playerId) {
        frozenPlayers.remove(playerId);
    }

    /**
     * Check if a player is frozen
     */
    public boolean isFrozen(UUID playerId) {
        return frozenPlayers.contains(playerId);
    }

    /**
     * Unfreeze all players (cleanup on disable)
     */
    public void unfreezeAll() {
        frozenPlayers.clear();
    }

